"""Bound the relative density of prime bases that might fail at any exponent or cofactor <=1000."""

from argparse import ArgumentParser
from fractions import Fraction
from functools import lru_cache
from math import gcd, prod

from carry_blocks import CarryGraph
from check_prime_power_cofactors import shapes
from check_shifted_directions import binomial_divisor, possible_scales
from check_shifted_prefixes import can_take
from search_endpoint import atoms, avoids, smallest_factors


DENOMINATORS = (364,380,589,629,646,703,710,738,780,850,874,880,946,950,962,986)
SPF = smallest_factors(15000)


def orbit_classes(mod, target):
    """Return (residue, first exponent, order) for every cyclic subgroup containing target."""
    for z in range(1, mod):
        if gcd(z, mod) != 1:
            continue
        e, value, first = 1, z, None
        while True:
            if value == target:
                first = e
            if value == 1:
                break
            value = value*z % mod
            e += 1
        if first is not None:
            yield z, first, e


def no_low_carry(parts, p, q):
    layer = p
    while layer <= q:
        if sum(x % layer for x in parts) >= layer:
            return False
        layer *= p
    return True


@lru_cache(maxsize=512)
def extendible_residues(slopes, offsets, p, q):
    """Low-digit blocks that extend to a finite carry-free integer."""
    graph = CarryGraph(p,slopes,offsets)
    reverse = [[] for _ in graph.states]
    for i, edges in enumerate(graph.edges):
        for _, j in edges:
            reverse[j].append(i)
    stack = [i for i in range(len(reverse)) if graph.accept & (1 << i)]
    live = set(stack)
    while stack:
        for i in reverse[stack.pop()]:
            if i not in live:
                live.add(i)
                stack.append(i)
    words = [(0,0)]
    place = 1
    while place < q:
        words = [(prefix+digit*place,j) for prefix,i in words
                 for digit,j in graph.edges[i] if j in live]
        place *= p
    return {v for v,_ in words}


def every_unit_carries(row, p):
    return all(sum(v*t % p for v in row) >= p for t in range(1,p))


def local_targets(m, shape, p, q, r, w):
    """Allowed values of W mod q=p^k, with its already prescribed residue mod w."""
    u, a, b, c, *row = shape
    u_power = gcd(q,u)
    assert (u//u_power) % p != 0 and q > u_power
    reduced = q//u_power
    inverse = pow(u//u_power,-1,reduced)
    m_power = dict(atoms(m,SPF)).get(p,1)
    needs_a = (u % p == 0 or
               (m_power > 1 and sum(x % m_power == 0 for x in row) < 2))
    needs_c = ((m_power > 1 and not can_take(m_power,p,a,b))
               or (p == 2 and m % 2 and u % 2))
    always_a_carries = binomial_divisor(a,b) % p == 0
    always_c_carries = (every_unit_carries(row,p) or any(
        binomial_divisor(row[i],row[j]) % p == 0 for i,j in ((0,1),(0,2),(1,2))))
    first_blocks = extendible_residues((a,b,c),(0,0,1),p,q)
    other_blocks = extendible_residues(tuple(row),(0,0,0),p,reduced)
    values = set()
    for t in range(r % w,q,w):
        if t % p == 0:
            continue  # The finitely many prime bases equal to local primes have density zero.
        n = m*t+1
        assert n % u_power == 0
        v = n//u_power*inverse % reduced
        if u_power > 1 and v % p == 0:
            continue
        good_a = not always_a_carries and t in first_blocks
        good_c = not always_c_carries and v in other_blocks
        if (good_a or good_c) and (good_a or not needs_a) and (good_c or not needs_c):
            values.add(t)
    return values


class PowerTest:
    """Test intersection of a multiplicative orbit with allowed residues at a prime power."""

    def __init__(self, p, q, targets):
        self.p, self.q, self.targets = p, q, targets
        self.projections = {}
        w = 1
        while w <= q:
            self.projections[w] = {t % w for t in targets}
            w *= p

    def __call__(self, initial, step):
        p, q = self.p, self.q
        # After a full period mod p (mod 4 for p=2), the remaining subgroup
        # generated by s fills precisely the multiples of gcd(s-1,q) above 1.
        bottom = min(q, 4 if p == 2 else p)
        multiplier = step
        length = 1
        while multiplier % bottom != 1:
            multiplier = multiplier*step % q
            length += 1
        common = gcd(multiplier-1,q)
        allowed = self.projections[common]
        value = initial
        for _ in range(length):
            if value % common in allowed:
                return True
            value = value*step % common
        return False


def base_fractions(m, shape, residue, modulus, depth, controls):
    local = []
    u = shape[0]
    primes = sorted({2} | {p for p,_ in atoms(u,SPF)+atoms(m,SPF)})
    # For any further prime at which C always carries, a factor of N
    # cannot lie in V. The resulting exclusion only needs one residue digit.
    extra = [p for p in range(3,u+1) if SPF[p] == p and p not in primes
             and every_unit_carries(shape[4:],p)]
    for p in extra:
        local.append((p,1,p,PowerTest(p,p,set(range(1,p))-{-pow(m,-1,p) % p})))
    for p in primes:
        w = dict(atoms(modulus,SPF)).get(p,1)
        q = w*p**depth
        targets = local_targets(m,shape,p,q,residue,w)
        local.append((p,w,q,PowerTest(p,q,targets)))

    def fraction(p,w,q,test,z,k,order):
        hits = total = 0
        for y in range(z % w,q,w):
            if y % p == 0:
                continue
            total += 1
            start = pow(y,k,q)
            step = pow(y,order,q)
            ok = test(start,step)
            if controls and q <= 125:
                value = start
                while value not in test.targets:
                    value = value*step % q
                    if value == start:
                        break
                assert ok == (value in test.targets)
            hits += ok
        return Fraction(hits,total)

    # Several old residue classes have identical projections to a local orbit.
    @lru_cache(None)
    def count(i,z,k,order):
        return fraction(*local[i],z,k,order)

    mass = Fraction()
    for z,k,order in orbit_classes(modulus,residue):
        contribution = Fraction(1)
        for i,(p,w,q,_) in enumerate(local):
            phi = q-q//p
            contribution *= count(i,z % w,k % phi,order % phi)
            if not contribution:
                break
        mass += contribution
    return mass/prod(w-w//p for p,w in atoms(modulus,SPF))


def odd_shapes():
    for m in DENOMINATORS:
        factors = atoms(m,SPF)
        for shape in shapes(m,factors):
            for parity,(residue,modulus),bases in possible_scales(m,factors,shape,SPF):
                if parity:
                    yield m,shape,residue,modulus,bases
                elif m % 2 and avoids(shape[1:4],2):
                    raise ArithmeticError(("power of two requires further checks",m,shape))


def exponent_growth(m, shape, forced):
    """Certify path growth by a positive integer vector on a carry graph."""
    numerator,denominator = (42,125) if m == 874 else (1,3)
    for p in sorted(forced):
        graph = CarryGraph(p,shape[1:4],(0,0,1))
        # Include every reachable state, even states that cannot finish.
        edges = [[j for _,j in row] for row in graph.edges]
        weights = [1]*len(edges)
        for _ in range(160):
            weights = [weights[i]+sum(weights[j] for j in row) for i,row in enumerate(edges)]
        if all(sum(weights[j] for j in row)**denominator
               <= p**numerator * weights[i]**denominator for i,row in enumerate(edges)):
            return p
    raise ArithmeticError(("path growth bound needs review",m,shape))


def verify(depth, controls):
    upper = Fraction()
    count = 0
    for m,shape,residue,modulus,forced in odd_shapes():
        growth_base = exponent_growth(m,shape,forced)
        density = base_fractions(m,shape,residue,modulus,depth,controls)
        print(f"d={m}, W={residue} mod {modulus}, density bound {density}, growth base {growth_base}",flush=True)
        count += 1
        upper += density
    print(f"{count} progressions. Exceptional prime bases have upper relative density "
          f"at most {upper} ({float(upper):.10f}).",flush=True)
    return upper


if __name__ == "__main__":
    cli = ArgumentParser(description=__doc__)
    cli.add_argument("--depth",type=int,default=2)
    cli.add_argument("--controls",action="store_true")
    args = cli.parse_args()
    if args.depth < 1:
        cli.error("use at least one additional layer")
    verify(args.depth,args.controls)
